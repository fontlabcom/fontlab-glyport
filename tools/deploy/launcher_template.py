# this_file: tools/deploy/launcher_template.py
# MenuTitle: Glyport Launcher
"""Run Glyphs scripts and plugin bundles in FontLab through glyport.

From the Scripts menu: choose "Run a Glyphs script…" or "Install a Glyphs plugin
bundle…", then the file or bundle. From FontLab Python code, after executing this
file with ``GLYPORT_LAUNCHER_NO_UI = True`` in its globals::

    launcher = sys.modules["_glyport_launcher"]
    handle = launcher.run_script("/path/Script.py")
    plugin = launcher.install_plugin("/path/Plugin.glyphsReporter")
    launcher.close_all()  # unload plugins, close script windows

Handles stay registered in that module, so plugins remain installed after the
launcher returns. Generated by tools/deploy/deploy_launcher.py; the two paths
below are this machine's glyport checkout and its dependency site directory.
"""

import sys
import types

GLYPORT_SRC = "@GLYPORT_SRC@"
GLYPORT_SITE = "@GLYPORT_SITE@"
STATE = "_glyport_launcher"
PURGED = ("fontlab_glyport", "GlyphsApp", "vanilla", "AppKit", "Foundation", "Cocoa")


def _owned(name):
    return any(name == root or name.startswith(root + ".") for root in PURGED)


def _live(state):
    return [
        h
        for h in state.handles
        if getattr(h, "state", None) != "closed"
    ]


def close_all():
    """Unload every plugin and close every script this launcher started."""
    state = sys.modules[STATE]
    failures = []
    for handle in reversed(state.handles):
        if getattr(handle, "state", None) == "closed":
            continue
        if getattr(handle, "state", None) == "failed":
            failures.append("Unresolved Glyport handle cleanup: failed")
            continue
        try:
            (getattr(handle, "unload", None) or handle.close)()
        except Exception as error:  # noqa: BLE001 - keep closing the rest; report all
            failures.append(f"{type(error).__name__}: {error}")
    state.handles[:] = _live(state)
    return failures


def activate(reload=False):
    """Put glyport first on sys.path and import it from GLYPORT_SRC.

    With an empty GLYPORT_SRC (deployed with ``--installed``) the installed
    fontlab_glyport is used as it is and no import path changes.

    Switching sources refuses while launcher handles remain live. With no live
    handles, stale canonical modules and their Fly aliases are purged together. ``reload=True``
    also purges this checkout's modules (to pick up edited code) when no
    plugin or script handle still uses them.
    """
    state = sys.modules[STATE]
    loaded = sys.modules.get("fontlab_glyport")
    current = loaded is not None and str(getattr(loaded, "__file__", "")).startswith(
        GLYPORT_SRC
    )
    if not current and _live(state):
        raise RuntimeError("Close all live Glyport handles before switching source")
    if not current or (reload and not _live(state)):
        close_all()
        fly = sys.modules.get("fly")
        if fly is not None:
            fly.__dict__.pop("gp", None)
        for name in [m for m in sys.modules if m == "fly.gp" or m.startswith("fly.gp.")]:
            del sys.modules[name]
        for name in [m for m in sys.modules if _owned(m)]:
            del sys.modules[name]
    for path in (GLYPORT_SRC, GLYPORT_SITE):
        while path and path in sys.path:
            sys.path.remove(path)
    sys.path[:0] = [p for p in (GLYPORT_SRC, GLYPORT_SITE) if p]
    from fly import gp

    if not gp.__file__.startswith(GLYPORT_SRC):
        raise ImportError(
            f"fontlab_glyport loaded from {gp.__file__}, not {GLYPORT_SRC}"
        )
    assert sys.modules["fontlab_glyport"] is gp, "Fly must share the canonical provider"
    return gp


def _has_python2_except(ast, tree, source):
    """True for ``except A, e:``, which Python 3.14 parses as a tuple of types.

    Python 3.14 (PEP 758) accepts an unparenthesised exception tuple, so
    ``ast.parse`` no longer rejects this Python 2 binding form. A Python 3 tuple is one
    parenthesised group; ``(A, B), e`` and ``A, e`` are not.
    """
    for node in ast.walk(tree):
        if isinstance(node, ast.ExceptHandler) and isinstance(node.type, ast.Tuple):
            segment = ast.get_source_segment(source, node.type) or ""
            if not _is_one_paren_group(segment):
                return True
    return False


def _is_one_paren_group(segment):
    """True when ``segment`` is a single balanced ``( ... )`` group."""
    if not segment.startswith("("):
        return False
    depth = 0
    for index, char in enumerate(segment):
        depth += (char == "(") - (char == ")")
        if depth == 0:
            return index == len(segment) - 1
    return False


def detect_profile(path):
    """``auto`` when every Python file parses as Python 3, else ``glyphs2``.

    Glyphs 2 ran Python 2; its scripts (print statements, ``except A, e``) need
    glyport's Glyphs 2 source adaptation. A bundle counts as one unit. For
    Python 3 source glyport chooses: declared versions and recognised version
    guards, else its runtime default Glyphs 4 (the issue-106 reference). Forcing
    ``glyphs3`` here made version-guarded scripts refuse (F48, s-hoi-dekinker).
    """
    import ast
    import os
    import warnings

    files = [path]
    if os.path.isdir(path):
        files = [
            os.path.join(d, f)
            for d, _, fs in os.walk(path)
            for f in fs
            if f.endswith(".py")
        ]
    for name in files:
        try:
            with open(name, encoding="utf-8", errors="replace") as stream:
                source = stream.read()
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", SyntaxWarning)
                tree = ast.parse(source)
            if _has_python2_except(ast, tree, source):
                return "glyphs2"
        except SyntaxError:
            return "glyphs2"
        except OSError:  # unreadable or missing: glyport reports the path itself
            continue
    return "auto"


def run_script(path, profile=None, dependency_paths=(), **options):
    """Run one Glyphs script; returns glyport's RunHandle (kept registered).

    ``profile=None`` picks auto or glyphs2 with ``detect_profile``.
    """
    glyport = activate()
    profile = profile or detect_profile(str(path))
    from fly.gp.entrypoints import ExecutionOptions

    if dependency_paths and "options" not in options:
        options["options"] = ExecutionOptions(
            dependency_paths=tuple(str(p) for p in dependency_paths)
        )
    handle = glyport.run_script(str(path), profile=profile, **options)
    sys.modules[STATE].handles.append(handle)
    return handle


def install_plugin(path, profile=None, **options):
    """Install one Glyphs plugin bundle; returns glyport's PluginHandle (kept registered)."""
    glyport = activate()
    profile = profile or detect_profile(str(path))
    handle = glyport.install_plugin(str(path), profile=profile, **options)
    sys.modules[STATE].handles.append(handle)
    return handle


def _choose():
    """Scripts-menu entry: ask what to do, then run it and report to Output."""
    from fly.qt import QtGui

    activate(reload=True)  # a fresh menu run picks up edited glyport code
    run, install, unload = (
        "Run a Glyphs script…",
        "Install a Glyphs plugin bundle…",
        "Unload all glyport plugins",
    )
    choice = QtGui.QInputDialog.getItem(
        None, "Glyport", "Action:", [run, install, unload], 0, False
    )
    if not choice:
        return
    if choice == unload:
        print("Glyport: unloaded;", close_all() or "no errors")
        return
    if choice == run:
        path = QtGui.QFileDialog.getOpenFileName(
            None, "Glyphs script", "", "Python (*.py)"
        )
        if path:
            print("Glyport:", run_script(path).state, path)
        return
    path = QtGui.QFileDialog.getExistingDirectory(
        None, "Glyphs plugin bundle (.glyphsPlugin, .glyphsReporter, …)"
    )
    if path:
        print("Glyport:", install_plugin(path).state, path)


_state = sys.modules.get(STATE)
if _state is None:
    _state = types.ModuleType(STATE)
    _state.handles = []
    sys.modules[STATE] = _state
for _name in (
    "activate",
    "close_all",
    "detect_profile",
    "run_script",
    "install_plugin",
):
    setattr(_state, _name, globals()[_name])
_state.GLYPORT_SRC, _state.GLYPORT_SITE = GLYPORT_SRC, GLYPORT_SITE

if not globals().get("GLYPORT_LAUNCHER_NO_UI"):
    _choose()
