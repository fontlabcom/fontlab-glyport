#!/usr/bin/env python3
# this_file: tools/deploy/deploy_launcher.py
"""Write a glyport launcher script into FontLab 9's Scripts folder (issue 106).

FontLab runs any ``.py`` file in its Scripts folder from the Scripts menu. The
launcher it writes puts this checkout's ``src`` (and an optional site directory
holding glyport's dependencies, e.g. fissix) first on ``sys.path``, purges stale
``fontlab_glyport``/``GlyphsApp``/``vanilla`` modules, and offers "run a Glyphs
script" / "install a Glyphs plugin bundle" for a chosen path. Its functions are
also callable from other FontLab Python code (see ``launcher_template.py``).

    python tools/deploy/deploy_launcher.py [--site DIR] [--scripts DIR] [--name NAME] [--force]

The default folder is the real ``~/Library/Application Support/FontLab/FontLab 9/Scripts``.
An existing file of the same name is replaced only when it is a launcher this
tool wrote (its marker line) or with ``--force``; anything else is refused.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
TEMPLATE = HERE / "launcher_template.py"
MARKER = "# glyport-launcher: generated by fontlab-glyport tools/deploy"
DEFAULT_SCRIPTS = Path.home() / "Library/Application Support/FontLab/FontLab 9/Scripts"
DEFAULT_NAME = "Glyport Launcher.py"


class DeployError(Exception):
    """The launcher cannot be written safely; the message says why."""


def render(src: Path | None, site: Path | None) -> str:
    """Launcher source with ``src``/``site`` embedded as absolute paths.

    ``src=None`` (``--installed``): the launcher uses whatever fontlab_glyport
    FontLab's Python already imports (e.g. an editable install in FontLab's
    ``python/3.11/site-packages``) and changes no import path.
    """
    if src is not None:
        src = src.resolve()
        if not (src / "fontlab_glyport/__init__.py").is_file():
            raise DeployError(f"not a glyport src directory: {src}")
    if site is not None and not site.resolve().is_dir():
        raise DeployError(f"site directory does not exist: {site}")
    lines = TEMPLATE.read_text(encoding="utf-8").splitlines(keepends=True)
    text = "".join(line for line in lines if not line.startswith("# this_file:"))
    text = text.replace('"@GLYPORT_SRC@"', repr(str(src) if src else ""))
    text = text.replace('"@GLYPORT_SITE@"', repr(str(site.resolve()) if site else ""))
    return MARKER + "\n" + text


def deploy(
    scripts: Path,
    *,
    src: Path | None = REPO / "src",
    site: Path | None = None,
    name: str = DEFAULT_NAME,
    force: bool = False,
) -> Path:
    """Write the launcher; return its path. Refuses unsafe targets."""
    if not name.endswith(".py") or "/" in name or name.startswith("."):
        raise DeployError(f"launcher name must be a plain .py file name: {name!r}")
    if not scripts.is_dir():
        raise DeployError(f"Scripts folder does not exist: {scripts}")
    if any(part == "fontlab-user-folder" for part in scripts.parts):
        raise DeployError(
            "write to the real Scripts folder, never through the fontlab-user-folder link"
        )
    target = scripts / name
    if target.is_symlink() or (target.exists() and not target.is_file()):
        raise DeployError(f"refusing to replace a link or directory: {target}")
    if target.exists() and not force:
        first = target.read_text(encoding="utf-8", errors="replace").splitlines()[:1]
        if first != [MARKER]:
            raise DeployError(
                f"name collides with a file this tool did not write: {target}"
            )
    text = render(src, site)
    compile(text, str(target), "exec")  # never deploy a launcher that cannot run
    staging = target.with_name("." + target.name + ".tmp")
    staging.write_text(text, encoding="utf-8")
    staging.replace(target)
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--scripts", type=Path, default=DEFAULT_SCRIPTS, help="FontLab Scripts folder"
    )
    parser.add_argument(
        "--src", type=Path, default=REPO / "src", help="glyport src directory"
    )
    parser.add_argument(
        "--site", type=Path, help="site directory with glyport's dependencies (fissix)"
    )
    parser.add_argument(
        "--installed",
        action="store_true",
        help="use the fontlab_glyport FontLab already imports (no src/site paths)",
    )
    parser.add_argument("--name", default=DEFAULT_NAME, help="launcher file name")
    parser.add_argument(
        "--force",
        action="store_true",
        help="replace a same-named file not written by this tool",
    )
    args = parser.parse_args(argv)
    try:
        path = deploy(
            args.scripts,
            src=None if args.installed else args.src,
            site=None if args.installed else args.site,
            name=args.name,
            force=args.force,
        )
    except DeployError as error:
        print(f"deploy_launcher: {error}", file=sys.stderr)
        return 1
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
